"""Live check: does REX Assistant really answer through the configured LLM (e.g. Groq)?

The test suite runs with LLM_PROVIDER=none, so it never proves that real LLM answers work.
This script sends a few fixed questions (English, Arabic, a course question, an unanswerable
question) and records, for each one, whether the reply came from the LLM, how long it took and
which sources it cited. Nothing is graded automatically: a person reads the answers.

    python -m evaluation.live_check                 # uses LLM_PROVIDER / key from .env
    python -m evaluation.live_check --label groq-gpt-oss-20b

Results are saved to evaluation/live/<timestamp>_<label>.json. Uses a temporary database, so it
never touches app data. Costs a few LLM calls (one or two per question).
"""
from __future__ import annotations

import argparse
import json
import os
import tempfile
import time
from datetime import datetime
from pathlib import Path

from src.agents.base import AgentRequest
from src.bootstrap import build_app
from src.config import PROJECT_ROOT, load_settings

QUESTIONS: list[tuple[str, list[str]]] = [
    ("recommend_en", ["I'm a fresh graduate, I want to work in software testing, I'm a beginner"]),
    ("recommend_ar", ["أنا خريج جديد وعايز أشتغل مطور تطبيقات موبايل"]),
    ("course_question", ["Who is the instructor for Flutter?"]),
    ("follow_up", ["I want to learn Flutter", "how many hours?"]),
    ("document_question", ["Is the academy accredited?"]),
    ("unanswerable", ["Does the academy offer scholarships for international students?"]),
]


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--label", default="live")
    args = ap.parse_args()

    load_settings()                       # loads .env into the environment (LLM provider, key, model)
    # ignore_cleanup_errors: on Windows the vector store may still hold a file when the folder is removed.
    with tempfile.TemporaryDirectory(ignore_cleanup_errors=True) as tmp:
        env = dict(os.environ)
        env.update({"DATABASE_URL": f"sqlite:///{Path(tmp) / 'live.db'}", "VECTOR_DIR": str(Path(tmp) / "vectors"),
                    "UPLOAD_DIR": str(Path(tmp) / "uploads")})
        settings = load_settings(env)
        ctx = build_app(settings)
        print(f"LLM status: {ctx.llm_status}\n")

        results = []
        for name, messages in QUESTIONS:
            state, reply, started = {}, None, time.perf_counter()
            for m in messages:
                reply = ctx.registry.dispatch("rex_assistant", AgentRequest.from_text(m, state))
                state = reply.state
            seconds = round(time.perf_counter() - started, 2)
            row = {"case": name, "messages": messages, "mode": reply.mode.value, "seconds": seconds,
                   "sources": [s.course_id or s.reference for s in reply.sources], "answer": reply.text}
            results.append(row)
            print(f"=== {name}  mode={row['mode']}  {seconds}s  sources={row['sources']}")
            print(f">> {' / '.join(messages)}\n{reply.text}\n")
        ctx.database.engine.dispose()     # release the SQLite file (Windows locks open files)

    out_dir = PROJECT_ROOT / "evaluation" / "live"
    out_dir.mkdir(parents=True, exist_ok=True)
    out = out_dir / f"{datetime.now():%Y%m%d-%H%M%S}_{args.label}.json"
    out.write_text(json.dumps({"llm_status": ctx.llm_status, "provider": settings.llm_provider,
                               "model": settings.llm_model, "results": results},
                              ensure_ascii=False, indent=1), encoding="utf-8")
    llm_count = sum(r["mode"] == "llm" for r in results)
    print(f"Replies generated by the LLM: {llm_count}/{len(results)}  ->  saved {out.relative_to(PROJECT_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
