"""Shared agent contract. Every REX AI agent consumes AgentRequest and returns AgentResponse.

This file is a SHARED INTERFACE (owned by Role 3). Changes require agreement from all roles.
"""
from __future__ import annotations

from abc import ABC, abstractmethod
from enum import Enum
from typing import Any, Literal

from pydantic import BaseModel, Field


class AgentStatus(str, Enum):
    IMPLEMENTED = "implemented"
    PLANNED = "planned"


class ResponseMode(str, Enum):
    LLM = "llm"                      # text generated by a real LLM call
    DETERMINISTIC = "deterministic"  # rule-based templates, no LLM involved
    ERROR = "error"


class AgentRequest(BaseModel):
    message: str = Field(min_length=1, max_length=4000)
    # Conversation state returned by the agent in a previous AgentResponse.state.
    state: dict[str, Any] = Field(default_factory=dict)

    @classmethod
    def from_text(cls, text: str, state: dict[str, Any] | None = None) -> "AgentRequest":
        return cls(message=text.strip(), state=state or {})


class SourceReference(BaseModel):
    """Where a fact came from: a structured course record or a page of an approved document."""
    source_type: Literal["course", "document"] = "course"
    reference: str
    course_id: str | None = None
    last_updated: str | None = None
    synthetic: bool = False
    document_id: str | None = None
    filename: str | None = None
    page: int | None = None
    score: float | None = None      # retrieval similarity, for document sources

    def label(self) -> str:
        if self.source_type == "document":
            return f"{self.filename}, p.{self.page}"
        return f"{self.course_id} ({'synthetic demo data' if self.synthetic else self.reference})"


class AgentResponse(BaseModel):
    agent_name: str
    text: str
    mode: ResponseMode
    language: str = "en"
    sources: list[SourceReference] = Field(default_factory=list)
    data: dict[str, Any] = Field(default_factory=dict)
    # Pass this back in the next AgentRequest.state to continue the conversation.
    state: dict[str, Any] = Field(default_factory=dict)


class AgentError(Exception):
    """Base class for agent failures."""


class Agent(ABC):
    name: str
    description: str

    @abstractmethod
    def handle(self, request: AgentRequest) -> AgentResponse:
        """Process one user turn."""
